#!/usr/bin/env python3
"""Write fritzfax/gui/germany.py: Germany's outline for the send animation.

    python3 -I tools/make_germany_outline.py ne_50m_admin_0_countries.geojson

Source: Natural Earth 1:50m Admin 0 countries (v5.1.2), public domain
(https://www.naturalearthdata.com/about/terms-of-use/). The main land and the two largest islands are
projected (equirectangular, scaled by cos 51 deg), simplified (Ramer-Douglas-Peucker) and normalized to
0..1, y pointing down.
"""
import json
import math
import sys
from pathlib import Path

TOLERANCE = 0.008  # degrees: a stylized outline, not a map; coarser leaves spikes at the estuaries
LAT0 = math.radians(51.0)


def rdp(points, eps):
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-12
    dist = [abs(dy * x - dx * y + x2 * y1 - y2 * x1) / norm for x, y in points[1:-1]]
    i = max(range(len(dist)), key=dist.__getitem__) + 1
    if dist[i - 1] > eps:
        return rdp(points[:i + 1], eps)[:-1] + rdp(points[i:], eps)
    return [points[0], points[-1]]


def simplify_ring(ring, eps):
    """RDP for a closed ring: split at the point farthest from the start, simplify both halves."""
    x0, y0 = ring[0]
    far = max(range(len(ring)), key=lambda i: math.hypot(ring[i][0] - x0, ring[i][1] - y0))
    return rdp(ring[:far + 1], eps)[:-1] + rdp(ring[far:], eps)


def main(path: str) -> int:
    data = json.loads(Path(path).read_text())
    (feature,) = [f for f in data["features"] if f["properties"].get("ADM0_A3") == "DEU"]
    rings = sorted((poly[0] for poly in feature["geometry"]["coordinates"]), key=len, reverse=True)[:3]
    projected = [[(lon * math.cos(LAT0), -lat) for lon, lat in ring] for ring in rings]
    simple = [simplify_ring(ring, TOLERANCE) for ring in projected]
    xs = [x for ring in simple for x, _ in ring]
    ys = [y for ring in simple for _, y in ring]
    x0, y0, size = min(xs), min(ys), max(max(xs) - min(xs), max(ys) - min(ys))
    norm = [[(round((x - x0) / size, 4), round((y - y0) / size, 4)) for x, y in ring] for ring in simple]
    out = Path(__file__).resolve().parent.parent / "fritzfax" / "gui" / "germany.py"
    lines = ['"""Germany\'s outline, normalized to 0..1 (y down). Generated by tools/make_germany_outline.py',
             'from Natural Earth (public domain). Do not edit by hand."""', "",
             f"WIDTH = {round((max(xs) - x0) / size, 4)}", f"HEIGHT = {round((max(ys) - y0) / size, 4)}",
             "RINGS = ["]
    for ring in norm:
        lines.append("    [")
        for i in range(0, len(ring), 6):
            lines.append("        " + ", ".join(f"({x}, {y})" for x, y in ring[i:i + 6]) + ",")
        lines.append("    ],")
    lines.append("]")
    out.write_text("\n".join(lines) + "\n")
    print(f"{out}: rings {[len(r) for r in norm]} (from {[len(r) for r in rings]})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
